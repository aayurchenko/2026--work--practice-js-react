// Задача 8. Массив в объект
// Преобразуй массив в объект, где ключом будет id пользователя,
// а значением — весь объект пользователя.
// Используй reduce().

const users = [
  { id: 1, name: 'Алексей' },
  { id: 2, name: 'Мария' },
  { id: 3, name: 'Олег' },
];

// Ожидаемый результат:
// {
//   1: { id: 1, name: 'Алексей' },
//   2: { id: 2, name: 'Мария' },
//   3: { id: 3, name: 'Олег' }
// }

// Твой код здесь

const res = users.reduce((res, key) => {
  res[key.id] = key;
  return res;
}, {})

console.log(res)